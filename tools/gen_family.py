def sample(rng):
    """One parameter set. Ranges bracket sensible student cutoffs; zero-inflated where a student
    would plausibly just not do the thing (bluff, slow-play, c-bet, float, bluff-raise)."""
    def maybe(p, hi):
        return round(rng.uniform(0, hi), 3) if rng.random() < p else 0.0
    pre_pot = rng.uniform(0.58, 0.70)
    val_pot = rng.uniform(0.62, 0.92)
    return {
        "samples": 100,
        "pre_pot": round(pre_pot, 3),
        "pre_raise": round(rng.uniform(0.46, pre_pot), 3),
        "pre_slack": round(rng.uniform(-0.06, 0.10), 3),
        "val_pot": round(val_pot, 3),
        "val_half": round(rng.uniform(0.48, min(0.70, val_pot - 0.03)), 3),
        "call_margin": round(rng.uniform(-0.08, 0.08), 3),
        "agg_disc": maybe(0.7, 0.07),
        "slow": maybe(0.4, 0.5),
        "half_pref": round(rng.random(), 3),
        "bluff_flop": maybe(0.5, 0.4),
        "bluff_turn": maybe(0.5, 0.4),
        "bluff_river": maybe(0.5, 0.4),
        "bluff_pot": round(rng.random(), 3),
        "cbet": maybe(0.6, 1.0),
        "float": maybe(0.5, 0.35),
        "bluff_raise": maybe(0.5, 0.15),
        "rng": rng.randrange(1, 10**6),
    }


def render(params):
    src = open(HONEST, encoding="utf-8").read()
    head = src[src.index(START):src.index(END)]
    if ROOT_LINE not in head:
        raise SystemExit("tools/opponents/honest.py changed shape: ROOT_LINE not found")
    head = head.replace(ROOT_LINE, "sys.path.insert(0, %r)" % ROOT)
    doc = '"""Generated by tools/gen_family.py (#89): equity-threshold bot with sampled PARAMS."""\n\n'
    return doc + head + BODY % {"params": json.dumps(params, indent=4)}


def generate(n, seed, out):
    os.makedirs(out, exist_ok=True)
    rng = random.Random(seed)
    fam, paths = {}, []
    for i in range(n):
        name = "fam_%s_%03d" % (seed, i)
        fam[name] = sample(rng)
        path = os.path.join(out, name + ".py")
        with open(path, "w", encoding="utf-8") as f:
            f.write(render(fam[name]))
        paths.append(path)
    with open(os.path.join(out, "family.json"), "w", encoding="utf-8") as f:
        json.dump(fam, f, indent=1)
    return paths, fam


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--n", type=int, default=40)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default=os.path.join(os.environ.get("DATA_DIR", "data"), "family"))
    a = ap.parse_args()
    paths, _ = generate(a.n, a.seed, a.out)
    print("wrote %d bots to %s" % (len(paths), a.out))


if __name__ == "__main__":
    main()
